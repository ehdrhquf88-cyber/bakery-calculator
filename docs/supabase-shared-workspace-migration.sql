create or replace function private.is_workspace_member(target_workspace_id uuid)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.workspace_members as members
    join public.workspaces as workspaces
      on workspaces.id = members.workspace_id
    where members.workspace_id = target_workspace_id
      and members.user_id = (select auth.uid())
      and members.is_active = true
      and workspaces.is_active = true
  );
$$;

revoke all on function private.is_workspace_member(uuid) from public, anon, authenticated;
grant execute on function private.is_workspace_member(uuid) to authenticated;

