create or replace function private.prevent_multiple_non_personal_workspaces()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  next_workspace_type public.workspace_type;
begin
  if new.is_active is not true then
    return new;
  end if;

  select type
  into next_workspace_type
  from public.workspaces
  where id = new.workspace_id;

  if next_workspace_type in ('shared'::public.workspace_type, 'company'::public.workspace_type)
    and exists (
      select 1
      from public.workspace_members as members
      join public.workspaces as workspaces
        on workspaces.id = members.workspace_id
      where members.user_id = new.user_id
        and members.workspace_id <> new.workspace_id
        and members.is_active = true
        and workspaces.is_active = true
        and workspaces.type in ('shared'::public.workspace_type, 'company'::public.workspace_type)
    )
  then
    raise exception 'Only one shared or company workspace membership is allowed.';
  end if;

  return new;
end;
$$;

revoke all on function private.prevent_multiple_non_personal_workspaces() from public, anon, authenticated;

drop trigger if exists on_workspace_members_prevent_multiple_non_personal on public.workspace_members;
create trigger on_workspace_members_prevent_multiple_non_personal
before insert or update on public.workspace_members
for each row execute function private.prevent_multiple_non_personal_workspaces();

create or replace function public.ensure_personal_workspace()
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_workspace_id uuid;
  user_email text;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required.';
  end if;

  select email
  into user_email
  from auth.users
  where id = (select auth.uid());

  select id
  into v_workspace_id
  from public.workspaces
  where owner_user_id = (select auth.uid())
    and type = 'personal'::public.workspace_type
    and is_active = true
  limit 1;

  if v_workspace_id is null then
    insert into public.workspaces (type, name, owner_user_id)
    values ('personal'::public.workspace_type, '개인 페이지', (select auth.uid()))
    returning id into v_workspace_id;
  end if;

  insert into public.workspace_members (workspace_id, user_id, email, role, is_active)
  values (v_workspace_id, (select auth.uid()), coalesce(user_email, ''), 'owner'::public.workspace_role, true)
  on conflict (workspace_id, user_id) do update
  set
    email = excluded.email,
    role = 'owner'::public.workspace_role,
    is_active = true,
    removed_at = null;

  update public.recipes
  set workspace_id = v_workspace_id
  where user_id = (select auth.uid())
    and workspace_id is null;

  update public.cost_items
  set workspace_id = v_workspace_id
  where user_id = (select auth.uid())
    and workspace_id is null;

  update public.temp_logs
  set workspace_id = v_workspace_id
  where user_id = (select auth.uid())
    and workspace_id is null;

  update public.deleted_items
  set workspace_id = v_workspace_id
  where user_id = (select auth.uid())
    and workspace_id is null;

  return v_workspace_id;
end;
$$;

revoke execute on function public.ensure_personal_workspace() from authenticated, anon, public;
grant execute on function public.ensure_personal_workspace() to authenticated;

create or replace function public.create_shared_workspace(workspace_name text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  workspace_id uuid;
  user_email text;
  normalized_workspace_name text;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required.';
  end if;

  if exists (
    select 1
    from public.workspace_members as members
    join public.workspaces as workspaces
      on workspaces.id = members.workspace_id
    where members.user_id = (select auth.uid())
      and members.is_active = true
      and workspaces.is_active = true
      and workspaces.type in ('shared'::public.workspace_type, 'company'::public.workspace_type)
  ) then
    raise exception 'Only one shared or company workspace membership is allowed.';
  end if;

  select email
  into user_email
  from auth.users
  where id = (select auth.uid());

  normalized_workspace_name := nullif(left(trim(coalesce(workspace_name, '')), 60), '');

  if normalized_workspace_name is null then
    raise exception 'Workspace name is required.';
  end if;

  insert into public.workspaces (type, name, owner_user_id)
  values ('shared'::public.workspace_type, normalized_workspace_name, (select auth.uid()))
  returning id into workspace_id;

  insert into public.workspace_members (workspace_id, user_id, email, role, is_active)
  values (workspace_id, (select auth.uid()), coalesce(user_email, ''), 'owner'::public.workspace_role, true);

  return workspace_id;
end;
$$;

revoke execute on function public.create_shared_workspace(text) from authenticated, anon, public;
grant execute on function public.create_shared_workspace(text) to authenticated;

create or replace function public.accept_workspace_invites_for_current_user()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  user_email text;
  invite record;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required.';
  end if;

  select email
  into user_email
  from auth.users
  where id = (select auth.uid());

  if user_email is null then
    return;
  end if;

  if exists (
    select 1
    from public.workspace_members as members
    join public.workspaces as workspaces
      on workspaces.id = members.workspace_id
    where members.user_id = (select auth.uid())
      and members.is_active = true
      and workspaces.is_active = true
      and workspaces.type in ('shared'::public.workspace_type, 'company'::public.workspace_type)
  ) then
    return;
  end if;

  for invite in
    select invites.workspace_id, invites.role
    from public.workspace_email_invites as invites
    join public.workspaces as workspaces
      on workspaces.id = invites.workspace_id
    where lower(invites.email) = lower(user_email)
      and invites.revoked_at is null
      and workspaces.is_active = true
      and workspaces.type in ('shared'::public.workspace_type, 'company'::public.workspace_type)
    order by invites.created_at asc
    limit 1
  loop
    insert into public.workspace_members (workspace_id, user_id, email, role, is_active)
    values (invite.workspace_id, (select auth.uid()), user_email, coalesce(invite.role, 'member'::public.workspace_role), true)
    on conflict (workspace_id, user_id) do update
    set
      email = excluded.email,
      role = excluded.role,
      is_active = true,
      removed_at = null;
  end loop;
end;
$$;

revoke execute on function public.accept_workspace_invites_for_current_user() from authenticated, anon, public;
grant execute on function public.accept_workspace_invites_for_current_user() to authenticated;

create or replace function public.revoke_workspace_invite(invite_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_invite record;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required.';
  end if;

  select id, workspace_id, email
  into target_invite
  from public.workspace_email_invites
  where id = invite_id;

  if target_invite.id is null then
    return;
  end if;

  if not (select private.can_manage_workspace(target_invite.workspace_id)) then
    raise exception 'Workspace management permission is required.';
  end if;

  update public.workspace_email_invites
  set revoked_at = coalesce(revoked_at, now())
  where id = target_invite.id;

  update public.workspace_members
  set
    is_active = false,
    removed_at = now()
  where workspace_id = target_invite.workspace_id
    and lower(email) = lower(target_invite.email)
    and role <> 'owner'::public.workspace_role;
end;
$$;

revoke execute on function public.revoke_workspace_invite(bigint) from authenticated, anon, public;
grant execute on function public.revoke_workspace_invite(bigint) to authenticated;

-- Repair already-revoked invite rows from earlier migration attempts:
-- a revoked email should not remain an active workspace member.
update public.workspace_members as members
set
  is_active = false,
  removed_at = coalesce(members.removed_at, invites.revoked_at, now())
from public.workspace_email_invites as invites
where members.workspace_id = invites.workspace_id
  and lower(members.email) = lower(invites.email)
  and members.role <> 'owner'::public.workspace_role
  and members.is_active = true
  and invites.revoked_at is not null;

