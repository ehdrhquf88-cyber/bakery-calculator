-- Supabase shared workspace migration for Levain Lab.
-- Run this after the public launch/auth setup has already been applied.
-- Phase 1 scope:
-- - personal workspace for every existing user
-- - one general shared workspace per user at most
-- - email pre-registration based membership
-- - workspace_id ownership for recipes, cost_items, temp_logs, deleted_items
-- Company/B2B, shared devices, and Stripe are intentionally excluded here.

create extension if not exists pgcrypto with schema extensions;

do $$
begin
  create type public.workspace_type as enum ('personal', 'shared', 'company');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.workspace_role as enum ('owner', 'member', 'admin', 'staff');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  type public.workspace_type not null default 'personal',
  name text not null,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint workspaces_name_not_blank_check
    check (length(trim(name)) > 0)
);

create table if not exists public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text not null,
  role public.workspace_role not null default 'member',
  is_active boolean not null default true,
  joined_at timestamptz not null default now(),
  removed_at timestamptz null,
  primary key (workspace_id, user_id)
);

create table if not exists public.workspace_email_invites (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  email text not null,
  role public.workspace_role not null default 'member',
  created_by uuid not null references auth.users(id) on delete cascade default auth.uid(),
  created_at timestamptz not null default now(),
  revoked_at timestamptz null,
  constraint workspace_email_invites_email_not_blank_check
    check (length(trim(email)) > 0)
);

create unique index if not exists workspaces_one_personal_per_owner_idx
on public.workspaces(owner_user_id)
where type = 'personal' and is_active = true;

create unique index if not exists workspaces_one_shared_per_owner_idx
on public.workspaces(owner_user_id)
where type = 'shared' and is_active = true;

create unique index if not exists workspace_email_invites_active_email_idx
on public.workspace_email_invites(lower(email))
where revoked_at is null;

create index if not exists workspace_members_user_id_idx
on public.workspace_members(user_id);

create index if not exists workspace_email_invites_workspace_id_idx
on public.workspace_email_invites(workspace_id);

create index if not exists workspace_email_invites_created_by_idx
on public.workspace_email_invites(created_by);

alter table public.recipes
  add column if not exists workspace_id uuid null references public.workspaces(id) on delete cascade;

alter table public.cost_items
  add column if not exists workspace_id uuid null references public.workspaces(id) on delete cascade;

alter table public.temp_logs
  add column if not exists workspace_id uuid null references public.workspaces(id) on delete cascade;

alter table public.deleted_items
  add column if not exists workspace_id uuid null references public.workspaces(id) on delete cascade;

drop index if exists recipes_workspace_id_id_idx;
create unique index recipes_workspace_id_id_idx
on public.recipes(workspace_id, id);

drop index if exists cost_items_workspace_id_id_idx;
create unique index cost_items_workspace_id_id_idx
on public.cost_items(workspace_id, id);

drop index if exists temp_logs_workspace_id_id_idx;
create unique index temp_logs_workspace_id_id_idx
